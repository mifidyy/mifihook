bool CreateMove::Hooked(void* self, float t, void* cmd) {
    const bool result = s_original(self, t, cmd);
    input::Apply(cmd);
    return result;
}

void CreateMove::Initialize() {
    LOG("Create Move is being Initialized...");

    target_address = GameBaseAdress + 0x015abf00;
    LOG("target_address = %p", (void*)target_address);

    s_original = nullptr;

    int rv = CreateHook();
    if (rv == 0) {
        // Copy the trampoline address generated by funchook into our static function pointer
        s_original = reinterpret_cast<CreateMoveFn>(m_original);
        LOG("Create Move hook installed successfully");
    } else {
        LOG("Failed to install Create Move hook, error: %d", rv);
    }
}

void CreateMove::Kill() {
    LOG("Create Move is being removed...");

    int rv = DestroyHook();

    if (rv != 0) {
        LOG("Create Move removing FAILED: %d", rv);
    }

    LOG("Create Move hook removed: %d", rv);
}

