bool BackstabDetect::Hooked(void* knife, void* target) {
    bool result = s_original(knife, target);
    
    LOG("knife=%p target=%p -> %d", knife, target, (int)result);
    
    return result;
}

void BackstabDetect::Initialize() {
    LOG("Backstab Detect is being Initialized...");

    target_address = GameBaseAdress + 0x1d2ea60;

    int rv = CreateHook();
    if (rv == 0) {
        // Copy the trampoline address generated by funchook into our static function pointer
        s_original = reinterpret_cast<CanBackstabFn>(m_original);
        LOG("BackstabDetect hook installed successfully");
    } else {
        LOG("Failed to install BackstabDetect hook, error: %d", rv);
    }
    LOG("BackstabDetect hook installed");
}

void BackstabDetect::Kill() {
    LOG("Backstab Detect is being removed...");

    DestroyHook();

    LOG("BackstabDetect hook removed");
}

